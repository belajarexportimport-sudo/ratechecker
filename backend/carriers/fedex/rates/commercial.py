# Base rate calculator - spesifik commercial (resolve zone lewat
# get_zone_commercial + alias/unavailable handling), lalu delegasikan
# perhitungan harga ke rate_common.price_from_table() yang generik/dipakai
# bareng rates_promotional.py.
# ---------------------------------------------------------------------------

def calculate_base(service, direction, country, weight_kg, leg_type="door_to_door",
                    apply_minimum=True, round_invoice=True, postal_code=None):
    """
    Hitung base rate COMMERCIAL (Exsis net rate; belum termasuk fuel/demand/
    ODA-OPA/special fees). Lihat rates.calculate_base() (facade) utk dispatch
    by rate_type - fungsi ini dipanggil dari sana kalau rate_type="commercial".

    country : nama negara PERSIS seperti di Zone Chart Commercial ATAU salah
              satu alias di COMMERCIAL_ALIASES (contoh: "Moldova", "Ivory
              Coast", "United States (Rest of Country)" semua otomatis
              diarahkan ke ejaan Exsis yang benar). Negara yang memang tidak
              ada rate commercial-nya (lihat COMMERCIAL_UNAVAILABLE_COUNTRIES)
              akan raise FedExRateError yang jelas.
    """
    service = service.upper()
    direction = direction.lower()

    if service not in COMMERCIAL_RATES.get(direction, {}):
        raise FedExRateError(f"Kombinasi service='{service}' direction='{direction}' tidak dikenal "
                              f"(didukung: IP, IE, IPF, IEF).")
    if weight_kg <= 0:
        raise FedExRateError("Berat harus > 0 kg.")

    zone, country_display, china_note = get_zone_commercial(
        country, direction, service, postal_code=postal_code)
    notes = [china_note] if china_note else []

    if zone not in COMMERCIAL_ZONES:
        raise FedExRateError(f"Zone '{zone}' tidak ada di tabel rate (commercial).")

    table = COMMERCIAL_RATES[direction][service]
    priced = price_from_table(table, zone, service, weight_kg, leg_type=leg_type,
                               apply_minimum=apply_minimum, round_invoice=round_invoice)
    if priced["min_kg_note"]:
        notes.append(priced["min_kg_note"])

    result = {k: v for k, v in priced.items() if k not in ("leg_type_used", "min_kg_note")}
    result.update({
        "service": service,
        "direction": direction,
        "country": country_display,
        "zone": zone,
        "leg_type": priced["leg_type_used"],
        "input_weight_kg": weight_kg,
        "notes": notes,
        "currency": "IDR",
        "rate_type": "commercial",
    })
    return result
