# ---------------------------------------------------------------------------
# Base rate calculator - spesifik promotional (resolve zone + China notes),
# lalu delegasikan perhitungan harga ke rate_common.price_from_table() yang
# generik/dipakai bareng rates_commercial.py.
# ---------------------------------------------------------------------------

def calculate_base(service, direction, country, weight_kg, leg_type="door_to_door",
                    apply_minimum=True, round_invoice=True, postal_code=None):
    """
    Hitung base rate PROMOTIONAL (belum termasuk fuel/demand/ODA-OPA/special
    fees). Lihat rates.calculate_base() (facade) utk dispatch by rate_type -
    fungsi ini dipanggil dari sana kalau rate_type="promotional" (default).

    service   : 'IP' | 'IPF' | 'IE' | 'IEF'   (IPE tidak didukung)
    direction : 'export' | 'import'
    country   : nama negara tujuan (export) / asal (import), sesuai Zone Index
    weight_kg : actual weight dalam kg
    leg_type  : hanya relevan utk IPF/IEF
    postal_code : kode pos di NEGARA TUJUAN/ASAL (bukan Indonesia). Khusus utk
                  China: kalau diisi & masuk range Fujian/Guangdong, Zone
                  otomatis jadi B.
    """
    service = service.upper()
    direction = direction.lower()

    if service not in RATES.get(direction, {}):
        raise FedExRateError(f"Kombinasi service='{service}' direction='{direction}' tidak dikenal "
                              f"(didukung: IP, IE, IPF, IEF).")
    if weight_kg <= 0:
        raise FedExRateError("Berat harus > 0 kg.")

    zone = get_zone(country, direction, service, postal_code=postal_code)
    country_display = find_country(country)["display_name"]

    notes = []
    if country_display == "China":
        is_south, region_label = resolve_china_zone(postal_code)
        if is_south:
            notes.append(f"Kode pos China '{postal_code}' masuk area {region_label} -> "
                          f"Zone B (bukan Zone C default).")
        elif postal_code:
            notes.append(f"Kode pos China '{postal_code}' di luar range Fujian "
                          f"(350000-369999) & Guangdong (510000-529999) -> "
                          f"Zone C (China Excluding China South).")
        else:
            notes.append("Kode pos China tidak diisi -> Zone diasumsikan C "
                          "(China Excluding China South). Kalau tujuan/asal di "
                          "Fujian/Guangdong, isi kode pos China supaya Zone B "
                          "terdeteksi otomatis.")

    if zone not in ZONES:
        raise FedExRateError(f"Zone '{zone}' tidak ada di tabel rate (promotional).")

    table = RATES[direction][service]
    priced = price_from_table(table, zone, service, weight_kg, leg_type=leg_type,
                               apply_minimum=apply_minimum, round_invoice=round_invoice)
    if priced["min_kg_note"]:
        notes.append(priced["min_kg_note"])

    result = {k: v for k, v in priced.items() if k not in ("leg_type_used", "min_kg_note")}
    result.update({
        "service": service,
        "direction": direction,
        "country": country_display,
        "zone": zone,
        "leg_type": priced["leg_type_used"],
        "input_weight_kg": weight_kg,
        "notes": notes,
        "currency": "IDR",
        "rate_type": "promotional",
    })
    return result
