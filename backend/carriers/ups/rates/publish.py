# ─────────────────────────────────────────────────────────────────────────────
# RAW RATE DATA (dari rates_data.js, sudah diparse ke dict)
# Format: RATES[direction][service][zone][weight_key] = price_idr
# weight_key: float untuk flat (<=20kg), int untuk per-kg (>20kg)
# ─────────────────────────────────────────────────────────────────────────────

def _parse_raw(raw: str) -> dict:
    """
    Parse tabel rate raw (tab-separated) ke dict.
    Kolom: weight | zone1 | zone2 | ... | zone10
    Baris range '>20kg' (mis. 21-44) disimpan dgn key = upper bound (44, 70, dst.)
    Baris Minimum disimpan dgn key 'min'.
    """
    result = {z: {} for z in range(1, 11)}
    for line in raw.strip().splitlines():
        line = line.strip().replace('\r', '')
        if not line:
            continue
        parts = line.replace('\t', ' ').split()
        if len(parts) < 2:
            continue
        if 'zone' in parts[0].lower():
            continue

        raw_wt = parts[0].strip('"').strip()

        # Minimum row
        if raw_wt.lower() in ('minimum', 'min'):
            for i in range(10):
                if i + 1 < len(parts):
                    price = int(parts[i + 1].replace('.', ''))
                    result[i + 1]['min'] = price
            continue

        # Range row (e.g. "21-44", "45-70", "71-99", "100-299", "300+")
        if '-' in raw_wt:
            upper = int(raw_wt.split('-')[1])
            wt_key = upper
        elif '+' in raw_wt or raw_wt == '300':
            wt_key = 300  # 300+
        else:
            # Flat weight: "1,0" or "1.5"
            wt_key = float(raw_wt.replace(',', '.'))

        for i in range(10):
            if i + 1 < len(parts):
                price_str = parts[i + 1].replace('.', '').replace(',', '')
                try:
                    price = int(price_str)
                    result[i + 1][wt_key] = price
                except ValueError:
                    pass

    return result


