def lookup_rate(direction: str, service: str, zone: int, weight_kg: float, rate_type: str = "publish"):
    """
    Cari rate untuk kombinasi direction/service/zone/weight.

    Return (rate, mode):
        mode = 'flat'  -> rate adalah harga total (bukan per-kg)
        mode = 'perkg' -> rate adalah harga per kg
    Return (None, None) jika tidak ditemukan.
    """
    table = RATES.get(direction, {}).get(service, {}).get(zone)
    if table is None:
        return None, None

    wt = weight_kg

    # Flat mode: cari key float yang cocok (<=20kg)
    if wt <= 20.0:
        # Cari key float terdekat (round up ke 0.5)
        rounded = round((wt * 2 + 0.999) // 1 / 2, 1)
        if rounded in table:
            return table[rounded], 'flat'
        # Fallback: cari key float paling kecil yang >= wt
        float_keys = sorted(k for k in table if isinstance(k, float))
        for k in float_keys:
            if k >= wt - 0.001:
                return table[k], 'flat'

    # Per-kg mode (>20kg atau weight di luar flat range)
    # Keys: 44 (range 21-44), 70 (45-70), 99 (71-99), 299 (100-299), 300 (300+)
    int_keys = sorted(k for k in table if isinstance(k, int) and k != 'min')
    for k in int_keys:
        if k == 300:
            if wt > 299:
                return table[k], 'perkg'
        else:
            if wt <= k:
                return table[k], 'perkg'

    return None, None
